#!/usr/bin/env node
/**
 * Generates docs/diagrams/catalog-erd.mmd from the live SQLite schema.
 *
 * Single source (writing rule R3): `SCHEMA_SQL` in `packages/bazaar/src/store.ts` —
 * the exact DDL `BazaarStore` applies on open. This script executes it against an
 * in-memory database and emits a mermaid erDiagram from `PRAGMA table_info` /
 * `PRAGMA foreign_key_list` / `PRAGMA index_list`, so the diagram cannot drift
 * from the schema the store actually creates.
 *
 * Run via `pnpm docs:gen`. Requires `pnpm build` first (imports the dist).
 */
import { writeFileSync, mkdirSync } from "node:fs";
import { resolve, dirname } from "node:path";
import { fileURLToPath } from "node:url";
import { DatabaseSync } from "node:sqlite";

const REPO_ROOT = resolve(dirname(fileURLToPath(import.meta.url)), "..", "..");
const OUT = resolve(REPO_ROOT, "docs", "diagrams", "catalog-erd.mmd");

const { SCHEMA_SQL } = await import(resolve(REPO_ROOT, "packages/bazaar/dist/store.js"));

const db = new DatabaseSync(":memory:");
db.exec(SCHEMA_SQL);

/** Tables declared directly in the DDL (skips FTS5 shadow tables). */
const tables = db
  .prepare(
    `SELECT name FROM sqlite_master
     WHERE type = 'table' AND name NOT LIKE 'sqlite_%' AND name NOT LIKE 'search_index_%'
     ORDER BY name`,
  )
  .all()
  .map(row => row.name);

const lines = [
  "%%{init: {'theme': 'neutral'}}%%",
  "%% GENERATED by scripts/docs/gen-erd.mjs from SCHEMA_SQL in packages/bazaar/src/store.ts.",
  "%% Do not edit. Regenerate with: pnpm docs:gen",
  "erDiagram",
];

/** table → Set of column names covered by a single-column unique index. */
const uniqueColumns = new Map();
for (const table of tables) {
  const set = new Set();
  try {
    for (const index of db.prepare(`PRAGMA index_list(${JSON.stringify(table)})`).all()) {
      if (!index.unique) continue;
      const cols = db.prepare(`PRAGMA index_info(${JSON.stringify(index.name)})`).all();
      if (cols.length === 1 && cols[0].name) set.add(cols[0].name);
    }
  } catch {
    /* virtual tables have no index_list */
  }
  uniqueColumns.set(table, set);
}

for (const table of tables) {
  const columns = db.prepare(`PRAGMA table_info(${JSON.stringify(table)})`).all();
  const foreignKeys = new Map();
  try {
    for (const fk of db.prepare(`PRAGMA foreign_key_list(${JSON.stringify(table)})`).all()) {
      foreignKeys.set(fk.from, fk);
    }
  } catch {
    /* virtual tables have no foreign_key_list */
  }

  lines.push(`  ${table} {`);
  for (const column of columns) {
    const type = column.type === "" ? "TEXT" : column.type.replaceAll(" ", "_");
    const markers = [];
    if (column.pk) markers.push("PK");
    if (foreignKeys.has(column.name)) markers.push("FK");
    else if (uniqueColumns.get(table)?.has(column.name)) markers.push("UK");
    const notes = [];
    if (column.notnull && !column.pk) notes.push("NOT NULL");
    if (column.dflt_value !== null && column.dflt_value !== undefined) {
      notes.push(`default ${column.dflt_value}`);
    }
    const suffix = markers.length > 0 ? ` ${markers.join(",")}` : "";
    const comment = notes.length > 0 ? ` "${notes.join("; ")}"` : "";
    lines.push(`    ${type} ${column.name}${suffix}${comment}`);
  }
  lines.push("  }");
}

// Relationships from the declared foreign keys.
for (const table of tables) {
  try {
    for (const fk of db.prepare(`PRAGMA foreign_key_list(${JSON.stringify(table)})`).all()) {
      lines.push(
        `  ${fk.table} ||--o{ ${table} : "${fk.from} -> ${fk.to ?? "id"}${
          fk.on_delete && fk.on_delete !== "NO ACTION" ? `, ON DELETE ${fk.on_delete}` : ""
        }"`,
      );
    }
  } catch {
    /* virtual tables have no foreign_key_list */
  }
}

// search_index is an FTS5 virtual table; SQLite tracks no FK for it. Its rowid
// is kept equal to resources.id in the same transaction as every catalog write
// (DECISIONS D-026), which is the one relationship PRAGMAs cannot see.
lines.push('  resources ||--|| search_index : "rowid = resources.id (D-026)"');

mkdirSync(dirname(OUT), { recursive: true });
writeFileSync(OUT, lines.join("\n") + "\n");
console.log(`gen-erd: wrote ${OUT} (${tables.length} tables)`);
