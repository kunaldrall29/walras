#!/usr/bin/env node
/**
 * Generates docs/reference/errors.md from the error-code enumerations.
 *
 * Single sources (writing rule R3): `packages/facilitator/src/errors.ts`
 * (inherited scheme codes + walras envelope codes and their canonical text),
 * `packages/bazaar/src/reasons.ts` (cataloging soft-drop codes), and
 * `packages/mcp-server/src/errors.ts` (MCP tool codes). The facilitator's
 * `errors.test.ts` greps the installed `@x402/stellar` bundle, so the inherited
 * enumeration cannot drift from upstream without failing the build.
 *
 * Run via `pnpm docs:gen`. Requires `pnpm build` first (imports the dists).
 */
import { writeFileSync, mkdirSync } from "node:fs";
import { resolve, dirname } from "node:path";
import { fileURLToPath } from "node:url";

const REPO_ROOT = resolve(dirname(fileURLToPath(import.meta.url)), "..", "..");
const OUT = resolve(REPO_ROOT, "docs", "reference", "errors.md");

const facilitator = await import(resolve(REPO_ROOT, "packages/facilitator/dist/errors.js"));
const bazaar = await import(resolve(REPO_ROOT, "packages/bazaar/dist/reasons.js"));
const mcp = await import(resolve(REPO_ROOT, "packages/mcp-server/dist/errors.js"));

/**
 * Renders a code → text table.
 *
 * @param codes - Ordered code list.
 * @param textFor - Function mapping a code to its canonical human-readable text.
 * @returns Markdown table.
 */
function renderTable(codes, textFor) {
  const lines = ["| Code | Meaning |", "| --- | --- |"];
  for (const code of codes) {
    lines.push(`| \`${code}\` | ${textFor(code).replaceAll("|", "\\|")} |`);
  }
  return lines.join("\n");
}

const content = `<!-- GENERATED by scripts/docs/gen-errors.mjs from the enumerations in
     packages/facilitator/src/errors.ts, packages/bazaar/src/reasons.ts, and
     packages/mcp-server/src/errors.ts. Do not edit. Regenerate with: pnpm docs:gen -->

# Error registry

Every rejection walras emits, on every path, carries a machine-readable code from
one of the disjoint taxonomies below plus a non-null human-readable reason
(RFP 3.6). Branch on the code; the text is an explanation, never a contract.

Taxonomy discipline (DECISIONS D-007, D-028): codes originated by
\`@x402/stellar\`'s payment scheme are passed through **verbatim** — walras never
invents a parallel name for a rejection the scheme already codes. \`walras_*\`
codes exist only for surfaces the scheme is silent about. A test greps the
installed \`@x402/stellar\` bundle for the inherited set, so upstream drift breaks
the build rather than silently degrading a rejection reason (FACTS F-063).

## Where codes appear

| Taxonomy | Appears in |
| --- | --- |
| Scheme verify codes | \`VerifyResponse.invalidReason\` (also settle, via mandatory re-verification) |
| Scheme settle codes | \`SettleResponse.errorReason\` |
| walras envelope codes | \`invalidReason\` / \`errorReason\` on 4xx/5xx; \`error.code\` on discovery endpoints |
| Bazaar soft-drop codes | the \`code\` field inside the \`EXTENSION-RESPONSES\` header's \`bazaar\` object |
| MCP tool codes | \`structuredContent.errorCode\` of an \`isError\` tool result |

## Inherited scheme codes — verify path (${facilitator.PACKAGE_VERIFY_REASON_CODES.length})

Emitted by \`ExactStellarScheme\` in \`@x402/stellar\` (FACTS F-045). The text
paraphrases the corresponding MUST in \`specs/schemes/exact/scheme_exact_stellar.md\`
at the pinned SHA. Note the reachability ordering of FACTS F-064: auth-entry and
transfer-event codes fire only after simulation succeeds, so on a network where
simulation cannot succeed, payloads collapse to
\`invalid_exact_stellar_payload_simulation_failed\`.

${renderTable(facilitator.PACKAGE_VERIFY_REASON_CODES, facilitator.reasonText)}

## Inherited scheme codes — settle path (${facilitator.PACKAGE_SETTLE_REASON_CODES.length})

${renderTable(facilitator.PACKAGE_SETTLE_REASON_CODES, facilitator.reasonText)}

## walras envelope codes (${facilitator.WALRAS_REASON_CODES.length})

Originated by the HTTP wrapper for what the scheme is silent about: envelope
validation, kind routing, discovery query interpretation, and wrapper faults.

${renderTable(facilitator.WALRAS_REASON_CODES, facilitator.reasonText)}

## Bazaar cataloging soft-drop codes (${bazaar.BAZAAR_REJECT_CODES.length})

Never appear in a payment response — only inside the \`bazaar\` object of the
\`EXTENSION-RESPONSES\` header, alongside the human-readable \`rejectedReason\`
the spec expects (FACTS F-024; DECISIONS D-014). Every code names a defect in
the client's payload; internal indexer faults omit the header entirely rather
than blaming the client (DECISIONS D-025).

${renderTable(bazaar.BAZAAR_REJECT_CODES, code => bazaar.BAZAAR_REJECT_TEXT[code])}

## MCP tool codes (${mcp.WALRAS_MCP_REASON_CODES.length})

Originated by \`packages/mcp-server\` for the surface only it owns (DECISIONS
D-028). Facilitator and scheme codes cross the MCP boundary verbatim; these
cover argument validation, id resolution, reachability, spend policy, and
payment outcomes the upstream leaves uncoded.

${renderTable(mcp.WALRAS_MCP_REASON_CODES, code => mcp.WALRAS_MCP_REASON_TEXT[code])}

## References

FACTS rows and DECISIONS entries cited above resolve in
[\`../FACTS.md\`](../FACTS.md) and [\`../DECISIONS.md\`](../DECISIONS.md).
`;

mkdirSync(dirname(OUT), { recursive: true });
writeFileSync(OUT, content);
const total =
  facilitator.PACKAGE_REASON_CODES.length +
  facilitator.WALRAS_REASON_CODES.length +
  bazaar.BAZAAR_REJECT_CODES.length +
  mcp.WALRAS_MCP_REASON_CODES.length;
console.log(`gen-errors: wrote ${OUT} (${total} codes across 4 taxonomies)`);
