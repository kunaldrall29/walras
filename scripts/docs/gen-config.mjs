#!/usr/bin/env node
/**
 * Generates docs/reference/config.md from the in-code configuration tables.
 *
 * Single sources (writing rule R3): `CONFIG_REFERENCE` in
 * `packages/facilitator/src/config.ts` and `packages/mcp-server/src/config.ts`.
 * Each package's `config-reference.test.ts` fails the build if its table drifts
 * from what `loadConfig` actually reads, so this document cannot silently lie.
 *
 * Run via `pnpm docs:gen`. Requires `pnpm build` first (imports the dists).
 */
import { writeFileSync, mkdirSync } from "node:fs";
import { resolve, dirname } from "node:path";
import { fileURLToPath } from "node:url";

const REPO_ROOT = resolve(dirname(fileURLToPath(import.meta.url)), "..", "..");
const OUT = resolve(REPO_ROOT, "docs", "reference", "config.md");

const facilitator = await import(resolve(REPO_ROOT, "packages/facilitator/dist/config.js"));
const mcpServer = await import(resolve(REPO_ROOT, "packages/mcp-server/dist/config.js"));

/**
 * Escapes a value for a Markdown table cell.
 *
 * @param text - Raw cell text.
 * @returns Pipe-safe cell text.
 */
function cell(text) {
  return String(text).replaceAll("|", "\\|").replaceAll("\n", " ");
}

/**
 * Renders one configuration table.
 *
 * @param reference - The package's CONFIG_REFERENCE entries.
 * @returns Markdown table.
 */
function renderTable(reference) {
  const lines = [
    "| Variable | Required | Default | Format | Description |",
    "| --- | --- | --- | --- | --- |",
  ];
  for (const entry of reference) {
    const name =
      entry.aliases && entry.aliases.length > 0
        ? `\`${entry.name}\` (alias: ${entry.aliases.map(a => `\`${a}\``).join(", ")})`
        : `\`${entry.name}\``;
    const defaultValue = entry.defaultValue === null ? "—" : `\`${entry.defaultValue}\``;
    lines.push(
      `| ${name} | ${cell(entry.required)} | ${cell(defaultValue)} | ${cell(entry.format)} | ${cell(entry.description)} |`,
    );
  }
  return lines.join("\n");
}

const content = `<!-- GENERATED by scripts/docs/gen-config.mjs from the CONFIG_REFERENCE tables in
     packages/facilitator/src/config.ts and packages/mcp-server/src/config.ts.
     Do not edit. Regenerate with: pnpm docs:gen -->

# Configuration reference

Both processes read plain environment variables (a \`.env\` file at the repository
root is loaded when present; real environment variables win). Invalid configuration
exits with code 78 (\`EX_CONFIG\`) before a port is bound or a tool is served — a
process that starts on half-valid configuration would advertise capability it
cannot honour.

Each table below is generated from a \`CONFIG_REFERENCE\` table that lives beside
the package's \`loadConfig\`; a unit test in each package fails if the table and
the loader drift apart.

## Facilitator (\`packages/facilitator\`)

${renderTable(facilitator.CONFIG_REFERENCE)}

## MCP server (\`packages/mcp-server\`)

${renderTable(mcpServer.CONFIG_REFERENCE)}

## References

FACTS rows and DECISIONS entries cited in the descriptions above resolve in
[\`../FACTS.md\`](../FACTS.md) and [\`../DECISIONS.md\`](../DECISIONS.md).
`;

mkdirSync(dirname(OUT), { recursive: true });
writeFileSync(OUT, content);
console.log(
  `gen-config: wrote ${OUT} (${facilitator.CONFIG_REFERENCE.length} facilitator vars, ${mcpServer.CONFIG_REFERENCE.length} mcp-server vars)`,
);
